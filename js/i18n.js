function showIndigenousComingSoon(code) {
  ensureNoticeStyle();
  document.getElementById('langFutureOverlay')?.remove();
  const name = (window.FUTURE_LANGS && window.FUTURE_LANGS[code]) || code;
  const overlay = document.createElement('div');
  overlay.id = 'langFutureOverlay';
  overlay.className = 'lang-future-overlay';
  overlay.innerHTML = `
    <div class="lang-future-card" role="dialog" aria-modal="true">
      <h3>${window.t('indigenous_coming_title', 'Próximamente')}</h3>
      <p><strong>${name}</strong> ${window.t('indigenous_coming', 'se integrará en un futuro.')}</p>
      <button type="button">${window.t('indigenous_ok', 'Entendido')}</button>
    </div>`;
  const close = () => overlay.remove();
  overlay.addEventListener('click', (e) => { if (e.target === overlay) close(); });
  overlay.querySelector('button').addEventListener('click', close);
  document.body.appendChild(overlay);
}

function showLanguageNotification(lang) {
  ensureNoticeStyle();
  document.querySelectorAll('.lang-toast').forEach((el) => el.remove());
  const notification = document.createElement('div');
  notification.className = 'lang-toast';
  notification.textContent = lang === 'es'
    ? 'Idioma cambiado a Español'
    : lang === 'guna'
      ? 'Gwabin: Dulegaya'
      : 'Language changed to English';
  document.body.appendChild(notification);
  requestAnimationFrame(() => { notification.style.transform = 'translateX(0)'; });
  setTimeout(() => {
    notification.style.transform = 'translateX(120%)';
    setTimeout(() => notification.remove(), 300);
  }, 2000);
}

