window.currentLang = function () {
  const lang = localStorage.getItem('lang') || 'es';
  if (window.translations && window.translations[lang]) return lang;
  return 'es';
};

window.t = function (key, fallback) {
  const lang = window.currentLang();
  const dict = window.translations && window.translations[lang];
  if (dict && dict[key]) return dict[key];
  const es = window.translations && window.translations.es;
  if (es && es[key]) return es[key];
  return fallback != null ? fallback : '';
};

window.applyI18nToRoot = function (root, lang) {
  if (!root) return;
  const dict = window.translations && window.translations[lang];
  if (!dict) return;

  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key || !dict[key]) return;
    if (el.tagName === 'OPTGROUP') {
      el.label = dict[key];
      return;
    }
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = dict[key];
      return;
    }
    if (el.tagName === 'TITLE') {
      el.textContent = dict[key];
      document.title = dict[key];
      return;
    }
    el.textContent = dict[key];
  });

  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (key && dict[key]) el.innerHTML = dict[key];
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key && dict[key]) el.setAttribute('aria-label', dict[key]);
  });

  root.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt');
    if (key && dict[key]) el.setAttribute('alt', dict[key]);
  });

  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key && dict[key]) el.setAttribute('title', dict[key]);
  });
};

