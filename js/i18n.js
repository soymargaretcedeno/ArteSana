window.setLanguage = function(lang, options) {
  options = options || {};
  const shouldNotify = options.notify === true;
  const future = window.FUTURE_LANGS || {};

  if (lang && future[lang]) {
    showIndigenousComingSoon(lang);
    return false;
  }

  if (!lang || !window.translations[lang]) {
    console.warn(`Idioma no válido: ${lang}`);
    return false;
  }

  localStorage.setItem('lang', lang);
  document.documentElement.setAttribute('lang', lang === 'guna' ? 'cuk' : lang);

  if (typeof window.applyI18nToRoot === 'function') {
    window.applyI18nToRoot(document, lang);
  }

  const components = [
    'header-component',
    'header-user-component', 
    'footer-component',
    'auth-modal',
    'platform-widgets'
  ];

  components.forEach((componentName) => {
    document.querySelectorAll(componentName).forEach((component) => {
      if (component.shadowRoot && typeof window.applyI18nToRoot === 'function') {
        window.applyI18nToRoot(component.shadowRoot, lang);
      }
      if (typeof component.updateI18nTexts === 'function') {
        try {
          component.updateI18nTexts();
        } catch (error) {
          console.warn(`Error actualizando ${componentName}:`, error);
        }
      }
    });
  });
  
  window.dispatchEvent(new Event('languageChanged'));
  
  if (shouldNotify) {
    showLanguageNotification(lang);
  }
  return true;
};

